// Writes src/runtimeText.ts: the Korean pieces of the messages the bundled runtime checker (AnimationInjectorXmlCheck,
// built from the runtime's Settings.cpp, XmlV2.cpp, Cards.cpp, ConditionFlowXml.cpp and RagdollProfile.cpp)
// writes. The checker joins Korean pieces and values ("알 수 없는 속성 '" + name + "'"), so the editor swaps each
// known piece for its translation (longest first) instead of matching whole sentences. Adjacent C++ literals count as one piece; a
// piece is split at {} format holes. Run again after the runtime changes a message, then translate what
// tools/i18n-merge.mjs --missing lists.
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import * as prettier from 'prettier';

const root = join(new URL('.', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'), '..');
const runtime = join(root, '..', 'AnimationInjector', 'src');
const sources = [
  'Settings.cpp',
  'declarations/XmlV2.cpp',
  'declarations/Cards.cpp',
  'declarations/ConditionFlowXml.cpp',
  'runtime/RagdollProfile.cpp',
];
const HANGUL = /[\uac00-\ud7a3]/;
const unescape = s => s.replace(/\\(["\\nt])/g, (_, c) => ({n: '\n', t: '\t'})[c] ?? c);

const pieces = new Set();
for (const file of sources) {
  const text = readFileSync(join(runtime, file), 'utf8')
    .replace(/\/\/[^\n]*/g, '')
    .replace(/\/\*[\s\S]*?\*\//g, '');
  // A run of adjacent string literals ("a" "b") is one C++ literal.
  for (const m of text.matchAll(/"(?:[^"\\\n]|\\.)*"(?:\s*"(?:[^"\\\n]|\\.)*")*/g)) {
    const literal = [...m[0].matchAll(/"((?:[^"\\\n]|\\.)*)"/g)].map(p => unescape(p[1])).join('');
    for (const piece of literal.split(/\{[^}]*\}/))
      if (HANGUL.test(piece) && piece.replace(/[^\uac00-\ud7a3]/g, '').length >= 2) pieces.add(piece);
  }
}
const quote = s => "'" + s.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('\n', '\\n') + "'";
const rows = [...pieces]
  .sort()
  .map(p => `  trFragment(${quote(p)}),`)
  .join('\n');
const out = `// Generated by tools/i18n-runtime.mjs from the runtime checker's sources: the Korean pieces its messages are made of.
// runtimeText() shows a checker message in the UI language (backend.ts and io.ts call it on checker output).
import {trFragment} from './i18n/korean.ts';

const pieces = [
${rows}
].sort((a, b) => b.ko.length - a.ko.length);

/** A runtime checker message with every known Korean piece in the UI language (values stay as they are). */
export function runtimeText(message: string): string {
  if (!/[\\uac00-\\ud7a3]/.test(message)) return message;
  let text = message;
  for (const piece of pieces) if (text.includes(piece.ko)) text = text.split(piece.ko).join(piece.show());
  return text;
}
`;
const target = join(root, 'src', 'runtimeText.ts');
const options = (await prettier.resolveConfig(target)) ?? {};
writeFileSync(target, await prettier.format(out, {...options, filepath: target}));
console.log('pieces', pieces.size);
