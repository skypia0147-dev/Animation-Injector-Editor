// Writes src/runtimeText.ts: the pieces of the messages the bundled runtime checker (AnimationInjectorXmlCheck,
// built from the runtime's Settings.cpp, XmlV2.cpp, Cards.cpp, ConditionFlowXml.cpp and RagdollProfile.cpp)
// writes, each with the Korean key of its row in the translation table. The checker writes English (11-24: the
// runtime's log is English) and joins pieces and values ("Unknown attribute '" + name + "'"), so the editor swaps
// each known piece for the UI language's (longest first) instead of matching whole sentences. Adjacent C++ literals
// count as one piece; a piece is split at {} format holes. A piece finds its row by the row's English: run again
// after the runtime changes a message, and give a new message a row (Korean key, then English as the runtime writes
// it) in src/i18n/fromKorean.ts; the pieces without one are listed.
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import * as prettier from 'prettier';

const root = join(new URL('.', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'), '..');
const runtime = join(root, '..', 'AnimationInjector', 'src');
const sources = [
  'Settings.cpp',
  'declarations/XmlV2.cpp',
  'declarations/Cards.cpp',
  'declarations/ConditionFlowXml.cpp',
  'runtime/RagdollProfile.cpp',
];
const {fromKorean} = await import(pathToFileURL(join(root, 'src', 'i18n', 'fromKorean.ts')).href);
const unescape = s => s.replace(/\\(["\\nt])/g, (_, c) => ({n: '\n', t: '\t'})[c] ?? c);

// English -> its Korean key; a key without a 「@use」 suffix first.
const korean = new Map();
for (const [ko, row] of Object.entries(fromKorean).sort(([a], [b]) => a.includes('@') - b.includes('@')))
  if (row[0] && !korean.has(row[0])) korean.set(row[0], ko);

const pieces = new Map(); // English piece -> Korean key
const unknown = new Set();
for (const file of sources) {
  const text = readFileSync(join(runtime, file), 'utf8')
    .replace(/\/\/[^\n]*/g, '')
    .replace(/\/\*[\s\S]*?\*\//g, '');
  // A run of adjacent string literals ("a" "b") is one C++ literal.
  for (const m of text.matchAll(/"(?:[^"\\\n]|\\.)*"(?:\s*"(?:[^"\\\n]|\\.)*")*/g)) {
    const literal = [...m[0].matchAll(/"((?:[^"\\\n]|\\.)*)"/g)].map(p => unescape(p[1])).join('');
    for (const piece of literal.split(/\{[^}]*\}/)) {
      // Words, not names: at least one space or 6 letters (a piece as short as "yes" would match inside values).
      if ((piece.match(/[A-Za-z]/g) ?? []).length < 3 || !/ |[A-Za-z]{6}/.test(piece)) continue;
      const ko = korean.get(piece);
      if (ko) pieces.set(piece, ko);
      else unknown.add(piece);
    }
  }
}
const quote = s => "'" + s.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('\n', '\\n') + "'";
const rows = [...pieces]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([en, ko]) => `  {en: ${quote(en)}, ...trFragment(${quote(ko)})},`)
  .join('\n');
const out = `// Generated by tools/i18n-runtime.mjs from the runtime checker's sources: the English pieces its messages are made
// of, each with its row's Korean key. runtimeText() shows a checker message in the UI language (backend.ts and io.ts
// call it on checker output).
import {getLanguage} from './i18n/index.ts';
import {trFragment} from './i18n/korean.ts';

// A piece matches as whole words: "Action" is not swapped inside an action id such as "MyAction".
const edge = (text: string, at: number) => /\\w/.test(text.charAt(at));
const pieces = [
${rows}
]
  .sort((a, b) => b.en.length - a.en.length)
  .map(piece => ({
    ...piece,
    pattern: new RegExp(
      (edge(piece.en, 0) ? '(?<!\\\\w)' : '') +
        piece.en.replace(/[.*+?^\${}()|[\\]\\\\]/g, '\\\\$&') +
        (edge(piece.en, piece.en.length - 1) ? '(?!\\\\w)' : ''),
      'g'
    ),
  }));

/** A runtime checker message with every known piece in the UI language (values stay as they are). */
export function runtimeText(message: string): string {
  if (getLanguage() === 'en') return message;
  let text = message;
  for (const piece of pieces) if (text.includes(piece.en)) text = text.replace(piece.pattern, () => piece.show());
  return text;
}
`;
const target = join(root, 'src', 'runtimeText.ts');
const options = (await prettier.resolveConfig(target)) ?? {};
writeFileSync(target, await prettier.format(out, {...options, filepath: target}));
console.log('pieces', pieces.size, 'without a row', unknown.size);
if (process.argv.includes('--unknown')) for (const piece of unknown) console.log('  ' + JSON.stringify(piece));
