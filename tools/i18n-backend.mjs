// Writes src/backendText.ts: the Korean messages the Rust backend (src-tauri/src, tests excluded) returns, as tr()
// patterns. Rust format arguments become placeholders: `{}` -> {v0}, {v1}…, `{name}` stays {name}.
// Run again after changing a backend message, then translate what tools/i18n-merge.mjs --missing lists.
import {readFileSync, readdirSync, statSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import * as prettier from 'prettier';

const root = join(new URL('.', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'), '..');
const HANGUL = /[가-힣]/;
const rust = dir =>
  readdirSync(dir).flatMap(name => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? rust(path) : name.endsWith('.rs') ? [path] : [];
  });

const patterns = new Set();
for (const file of rust(join(root, 'src-tauri', 'src')).sort()) {
  let text = readFileSync(file, 'utf8');
  const tests = text.indexOf('#[cfg(test)]');
  if (tests >= 0) text = text.slice(0, tests);
  // A raw string (r"\\?\") is skipped whole: read as an ordinary one, its backslash would shift every quote after it.
  for (const m of text.matchAll(/r(#*)"[\s\S]*?"\1|"((?:[^"\\]|\\.)*)"/g)) {
    const literal = m[2];
    if (literal === undefined || !HANGUL.test(literal)) continue;
    let n = 0;
    const pattern = literal
      .replace(/\\"/g, '"')
      .replace(/\{\{/g, '\u0001')
      .replace(/\}\}/g, '\u0002')
      .replace(/\{([A-Za-z_]\w*)?(?::[^}]*)?\}/g, (_, name) => '{' + (name ?? 'v' + n++) + '}')
      .replace(/\u0001/g, '{')
      .replace(/\u0002/g, '}');
    patterns.add(pattern);
  }
}
const quote = s => "'" + s.replaceAll('\\', '\\\\').replaceAll("'", "\\'") + "'";
const rows = [...patterns]
  .sort()
  .map(p => `  trPattern(${quote(p)}),`)
  .join('\n');
const out = `// Generated by tools/i18n-backend.mjs from src-tauri/src: the messages the Rust backend returns, in Korean.
// backendText() shows one in the UI language (src/backend.ts calls it on every backend error and message).
import {trPattern} from './i18n/korean.ts';

const patterns = [
${rows}
];

const escape = (s: string) => s.replace(/[.*+?^$()|[\\]\\\\]/g, '\\\\$&');
const compiled = patterns
  .map(({pattern, show}) => {
    const names: string[] = [];
    const parts = pattern.split(/\\{(\\w+)\\}/);
    let source = '';
    parts.forEach((part, i) => {
      if (i % 2) {
        names.push(part);
        source += i === parts.length - 2 && !parts[i + 1] ? '([\\\\s\\\\S]*)' : '([\\\\s\\\\S]*?)';
      } else source += escape(part);
    });
    return {regex: new RegExp('^' + source + '([\\\\s\\\\S]*)$'), names, show, weight: parts.filter((_, i) => i % 2 === 0).join('').length};
  })
  .sort((a, b) => b.weight - a.weight);

/** A backend message in the UI language. A message that starts with a known one keeps the rest as it is. */
export function backendText(message: string): string {
  for (const {regex, names, show} of compiled) {
    const match = regex.exec(message);
    if (!match) continue;
    const vars = Object.fromEntries(names.map((name, i) => [name, match[i + 1]]));
    return show(vars) + match[names.length + 1];
  }
  return message;
}
`;
const target = join(root, 'src', 'backendText.ts');
const options = (await prettier.resolveConfig(target)) ?? {};
writeFileSync(target, await prettier.format(out, {...options, filepath: target}));
console.log('patterns', patterns.size);
